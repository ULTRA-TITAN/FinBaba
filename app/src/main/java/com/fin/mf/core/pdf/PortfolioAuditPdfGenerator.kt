    }

    private fun formatPct(pct: Double): String {
        return String.format(Locale.US, "%.1f%%", pct)
    }

    private fun getDriftLabel(actual: Double, target: Double): String {
        val diff = actual - target
        return when {
            kotlin.math.abs(diff) <= 2.0 -> "Balanced"
            diff > 0 -> "+${String.format(Locale.US, "%.1f%%", diff)} Over"
            else -> "-${String.format(Locale.US, "%.1f%%", kotlin.math.abs(diff))} Under"
        }
    }

    private data class Tuple5(val a: String, val b: String, val c: String, val d: String, val e: String)
}
