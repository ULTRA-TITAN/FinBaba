/**
 * High-performance, zero-dependency offline native PDF audit generator for FinBaba.
 * Uses Android's native `android.graphics.pdf.PdfDocument` to author clean, institutional-grade
 * 2-page A4 audit reports ready for printing, archiving, or sharing via standard system intents.
 */
object PortfolioAuditPdfGenerator {

    private const val PAGE_WIDTH = 595 // Standard A4 width in 72 DPI points
    private const val PAGE_HEIGHT = 842 // Standard A4 height in 72 DPI points

    private val inrFormatter: NumberFormat = NumberFormat.getCurrencyInstance(Locale("en", "IN")).apply {
        maximumFractionDigits = 0
    }

    /**
     * Generates a comprehensive 2-page PDF audit report and triggers the system share/view sheet.
     */
    fun generateAndSharePdf(
        context: Context,
        portfolioData: PortfolioData,
        analytics: PortfolioAnalyticsSummary,
        healthScore: Int,
        onSuccess: ((File, Uri) -> Unit)? = null,
        onError: ((Throwable) -> Unit)? = null
    ) {
        try {
            val pdfDoc = PdfDocument()

            // ----------------------------------------------------
            // PAGE 1: Executive Summary, SEBI Cap, Top 8 Sectors
            // ----------------------------------------------------
            val pageInfo1 = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, 1).create()
            val page1 = pdfDoc.startPage(pageInfo1)
            renderPageOne(page1.canvas, portfolioData, analytics, healthScore)
            pdfDoc.finishPage(page1)

            // ----------------------------------------------------
            // PAGE 2: Counterparty Overlap, Scheme Details, Footer
            // ----------------------------------------------------
            val pageInfo2 = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, 2).create()
            val page2 = pdfDoc.startPage(pageInfo2)
            renderPageTwo(page2.canvas, portfolioData, analytics)
            pdfDoc.finishPage(page2)

            // Persist to cache directory
            val timeStamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US).format(Date())
            val targetFile = File(context.cacheDir, "FinBaba_Portfolio_Audit_$timeStamp.pdf")
            val outputStream = FileOutputStream(targetFile)
            pdfDoc.writeTo(outputStream)
            outputStream.flush()
            outputStream.close()
            pdfDoc.close()

            // Share via FileProvider
            val contentUri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                targetFile
            )

            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_STREAM, contentUri)
                putExtra(Intent.EXTRA_SUBJECT, "FinBaba Portfolio Audit - ${portfolioData.portfolioName}")
                putExtra(
                    Intent.EXTRA_TEXT,
                    "Portfolio Audit Report generated by FinBaba for ${portfolioData.ownerName} (${portfolioData.schemes.size} active schemes)."
                )
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }

            val chooser = Intent.createChooser(shareIntent, "Share FinBaba Audit Report").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(chooser)

            Toast.makeText(context, "Audit Report Generated & Ready to Share!", Toast.LENGTH_SHORT).show()
            onSuccess?.invoke(targetFile, contentUri)
        } catch (t: Throwable) {
            t.printStackTrace()
            Toast.makeText(context, "Failed to generate PDF: ${t.localizedMessage}", Toast.LENGTH_LONG).show()
            onError?.invoke(t)
        }
    }

    private fun renderPageOne(
        canvas: Canvas,
        portfolio: PortfolioData,
        analytics: PortfolioAnalyticsSummary,
        healthScore: Int
    ) {
        val paint = Paint(Paint.ANTI_ALIAS_FLAG)

        // 1. Top Brand Banner Header
        paint.color = AndroidColor.rgb(30, 58, 138) // Deep Navy (#1E3A8A)
        canvas.drawRect(0f, 0f, PAGE_WIDTH.toFloat(), 64f, paint)

        // Top Brand Accent Line
        paint.color = AndroidColor.rgb(37, 99, 235) // Royal Blue (#2563EB)
        canvas.drawRect(0f, 64f, PAGE_WIDTH.toFloat(), 68f, paint)

        // Header Title
        paint.color = AndroidColor.WHITE
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 18f
        canvas.drawText("FinBaba FINANCIAL STUDIO", 32f, 32f, paint)

        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        paint.textSize = 9f
        paint.color = AndroidColor.rgb(203, 213, 225)
        canvas.drawText("${portfolio.portfolioName.uppercase()} — PORTFOLIO X-RAY & HEALTH AUDIT", 32f, 48f, paint)

        // Header Right: Date & Portfolio Name
        val dateString = SimpleDateFormat("dd MMMM yyyy, hh:mm a", Locale.US).format(Date())
        paint.textAlign = Paint.Align.RIGHT
        paint.color = AndroidColor.WHITE
        paint.textSize = 10f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText(portfolio.portfolioName, PAGE_WIDTH - 32f, 30f, paint)

        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        paint.textSize = 8.5f
        paint.color = AndroidColor.rgb(203, 213, 225)
        canvas.drawText("Investor: ${portfolio.ownerName} • Generated: $dateString", PAGE_WIDTH - 32f, 46f, paint)
        paint.textAlign = Paint.Align.LEFT

        // 2. Executive Metric Pillars (4-Card Row)
        var curY = 92f
        val cardWidth = (PAGE_WIDTH - 64f - 24f) / 4f
        val cardHeight = 58f

        val metrics = listOf(
            Triple("PORTFOLIO VALUE", inrFormatter.format(analytics.totalCurrentValue), AndroidColor.rgb(15, 23, 42)),
            Triple("INVESTED PRINCIPAL", inrFormatter.format(analytics.totalInvested), AndroidColor.rgb(15, 23, 42)),
            Triple(
                "NET CAPITAL RETURN",
                "${if (analytics.totalGain >= 0) "+" else ""}${formatPct(analytics.totalReturnPercent)}",
                if (analytics.totalGain >= 0) AndroidColor.rgb(5, 150, 105) else AndroidColor.rgb(220, 38, 38)
            ),
            Triple("HEALTH SCORE", "$healthScore / 100", AndroidColor.rgb(37, 99, 235))
        )

        for (i in metrics.indices) {
            val left = 32f + i * (cardWidth + 8f)
            val rect = RectF(left, curY, left + cardWidth, curY + cardHeight)

            // Card background
            paint.color = AndroidColor.rgb(248, 250, 252)
            canvas.drawRoundRect(rect, 6f, 6f, paint)

            // Card border
            paint.style = Paint.Style.STROKE
            paint.strokeWidth = 1f
            paint.color = AndroidColor.rgb(226, 232, 240)
            canvas.drawRoundRect(rect, 6f, 6f, paint)
            paint.style = Paint.Style.FILL

            // Metric Label
            paint.color = AndroidColor.rgb(100, 116, 139)
            paint.textSize = 7.5f
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            canvas.drawText(metrics[i].first, left + 8f, curY + 16f, paint)

            // Metric Value
            paint.color = metrics[i].third
            paint.textSize = 12f
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            canvas.drawText(metrics[i].second, left + 8f, curY + 38f, paint)

            // Metric subtext
            paint.color = AndroidColor.rgb(148, 163, 184)
            paint.textSize = 6.5f
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            val sub = when (i) {
                0 -> "${portfolio.schemes.size} Active Mutual Funds"
                1 -> "Principal Cost Basis"
                2 -> "Absolute INR: ${if (analytics.totalGain >= 0) "+" else ""}${inrFormatter.format(analytics.totalGain)}"
                else -> if (healthScore >= 80) "Institutional Grade" else "Review Suggested"
            }
            canvas.drawText(sub, left + 8f, curY + 50f, paint)
        }

        curY += cardHeight + 24f

        // 3. SEBI Market Cap Alignment Table
        paint.color = AndroidColor.rgb(15, 23, 42)
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("1. SEBI MARKET CAPITALIZATION ALIGNMENT", 32f, curY, paint)

        curY += 12f
        paint.color = AndroidColor.rgb(100, 116, 139)
        paint.textSize = 8f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Benchmark strategic target: 50% Large Cap / 25% Mid Cap / 25% Small Cap", 32f, curY, paint)

        curY += 10f

        // Table Header
        drawTableRow(
            canvas = canvas,
            paint = paint,
            y = curY,
            isHeader = true,
            c1 = "Market Cap Category",
            c2 = "Portfolio Weight %",
            c3 = "Total Value",
            c4 = "Strategic Target",
            c5 = "Status & Drift"
        )
        curY += 18f

        // Table Rows
        val largeSlice = analytics.marketCapBreakdown.firstOrNull { it.label.contains("Large", ignoreCase = true) }
        val midSlice = analytics.marketCapBreakdown.firstOrNull { it.label.contains("Mid", ignoreCase = true) }
        val smallSlice = analytics.marketCapBreakdown.firstOrNull { it.label.contains("Small", ignoreCase = true) }
        val microSlice = analytics.marketCapBreakdown.firstOrNull { it.label.contains("Micro", ignoreCase = true) || it.label.contains("Tail", ignoreCase = true) }

        val largeWeight = largeSlice?.weightPercent ?: 0.0
        val midWeight = midSlice?.weightPercent ?: 0.0
        val smallWeight = smallSlice?.weightPercent ?: 0.0
        val microWeight = microSlice?.weightPercent ?: 0.0

        val capRows = listOf(
            Tuple5("Large Cap (Top 100 Listed)", formatPct(largeWeight), inrFormatter.format(largeSlice?.rupeeValue ?: 0.0), "50.0%", getDriftLabel(largeWeight, 50.0)),
            Tuple5("Mid Cap (101 - 250 Listed)", formatPct(midWeight), inrFormatter.format(midSlice?.rupeeValue ?: 0.0), "25.0%", getDriftLabel(midWeight, 25.0)),
            Tuple5("Small Cap (251 - 500 Listed)", formatPct(smallWeight), inrFormatter.format(smallSlice?.rupeeValue ?: 0.0), "25.0%", getDriftLabel(smallWeight, 25.0)),
            Tuple5("Micro, Debt & Arbitrage", formatPct(microWeight), inrFormatter.format(microSlice?.rupeeValue ?: 0.0), "0.0%", if (microWeight <= 1.0) "Balanced" else "+${formatPct(microWeight)} Tail")
        )

        for (row in capRows) {
            drawTableRow(canvas, paint, curY, false, row.a, row.b, row.c, row.d, row.e)
            curY += 16f
        }

        // Advisory Note Box
        curY += 6f
        val noteRect = RectF(32f, curY, PAGE_WIDTH - 32f, curY + 24f)
        paint.color = AndroidColor.rgb(239, 246, 255)
        canvas.drawRoundRect(noteRect, 4f, 4f, paint)
        paint.color = AndroidColor.rgb(30, 58, 138)
        paint.textSize = 7.5f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Audit Note: Market cap exposures reflect true look-through constituents aggregated across all ${portfolio.schemes.size} active funds.", 40f, curY + 15f, paint)

        curY += 40f

        // 4. Sector Exposure Breakdown Table (Top 8)
        paint.color = AndroidColor.rgb(15, 23, 42)
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("2. SECTOR CONCENTRATIONS & DIVERSIFICATION", 32f, curY, paint)

        curY += 12f
        paint.color = AndroidColor.rgb(100, 116, 139)
        paint.textSize = 8f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("True underlying industry exposure ranked by aggregate AUM weighting", 32f, curY, paint)

        curY += 10f

        // Sector Table Header
        drawSectorRow(
            canvas = canvas,
            paint = paint,
            y = curY,
            isHeader = true,
            rank = "#",
            name = "Economic Sector",
            instruments = "Instruments",
            weight = "Portfolio Weight %",
            rupees = "Rupee Exposure"
        )
        curY += 18f

        // Sector Rows
        val topSectors = analytics.sectorBreakdown.take(8)
        for (idx in topSectors.indices) {
            val sector = topSectors[idx]
            drawSectorRow(
                canvas = canvas,
                paint = paint,
                y = curY,
                isHeader = false,
                rank = String.format(Locale.US, "%02d", idx + 1),
                name = sector.sectorName,
                instruments = "${sector.stockCount} Securities",
                weight = formatPct(sector.portfolioWeightPercent),
                rupees = inrFormatter.format(sector.totalRupeeValue)
            )
            curY += 16f
        }

        // Bottom Page 1 Marker
        paint.color = AndroidColor.rgb(148, 163, 184)
        paint.textSize = 8f
        paint.textAlign = Paint.Align.RIGHT
        canvas.drawText("Page 1 of 2 • FinBaba Portfolio Diagnostic Audit", PAGE_WIDTH - 32f, PAGE_HEIGHT - 24f, paint)
        paint.textAlign = Paint.Align.LEFT
    }

    private fun renderPageTwo(
        canvas: Canvas,
        portfolio: PortfolioData,
        analytics: PortfolioAnalyticsSummary
    ) {
        val paint = Paint(Paint.ANTI_ALIAS_FLAG)

        // 1. Top Brand Banner Header Page 2
        paint.color = AndroidColor.rgb(30, 58, 138)
        canvas.drawRect(0f, 0f, PAGE_WIDTH.toFloat(), 50f, paint)

        paint.color = AndroidColor.rgb(37, 99, 235)
        canvas.drawRect(0f, 50f, PAGE_WIDTH.toFloat(), 53f, paint)

        paint.color = AndroidColor.WHITE
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        paint.textSize = 14f
        canvas.drawText("FinBaba PORTFOLIO AUDIT • PAGE 2", 32f, 28f, paint)

        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        paint.textSize = 8.5f
        paint.color = AndroidColor.rgb(203, 213, 225)
        canvas.drawText("COUNTERPARTY CONCENTRATION & FUND-BY-FUND CONSTITUENT MATRIX", 32f, 42f, paint)

        paint.textAlign = Paint.Align.RIGHT
        paint.color = AndroidColor.WHITE
        paint.textSize = 9f
        canvas.drawText("${portfolio.schemes.size} Schemes • ${analytics.topHoldings.size} Unique Securities", PAGE_WIDTH - 32f, 32f, paint)
        paint.textAlign = Paint.Align.LEFT

        var curY = 76f

        // 2. Counterparty Overlap Alert Section
        paint.color = AndroidColor.rgb(15, 23, 42)
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("3. HIGH DUPLICATE OVERLAP & CONCENTRATION", 32f, curY, paint)

        curY += 12f
        paint.color = AndroidColor.rgb(100, 116, 139)
        paint.textSize = 8f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Securities held redundantly across 3 or more of your active mutual funds", 32f, curY, paint)

        curY += 10f

        // Overlap Table Header
        drawOverlapRow(
            canvas = canvas,
            paint = paint,
            y = curY,
            isHeader = true,
            ticker = "Ticker",
            company = "Company Name",
            sector = "Sector",
            cap = "Cap Tier",
            funds = "Held In",
            weight = "Weight %",
            rupees = "Rupee Exposure"
        )
        curY += 18f

        val highOverlapStocks = analytics.topHoldings.filter { it.heldInSchemesCount >= 3 }.take(6)
        if (highOverlapStocks.isEmpty()) {
            paint.color = AndroidColor.rgb(5, 150, 105)
            paint.textSize = 9f
            canvas.drawText("No redundant securities held in 3+ funds detected. Single-stock concentration is well balanced.", 32f, curY + 12f, paint)
            curY += 26f
        } else {
            for (stock in highOverlapStocks) {
                drawOverlapRow(
                    canvas = canvas,
                    paint = paint,
                    y = curY,
                    isHeader = false,
                    ticker = stock.ticker,
                    company = stock.companyName.take(20),
                    sector = stock.sector.take(16),
                    cap = stock.marketCapBucket,
                    funds = "${stock.heldInSchemesCount} Funds",
                    weight = formatPct(stock.portfolioWeightPercent),
                    rupees = inrFormatter.format(stock.totalRupeeExposure)
                )
                curY += 16f
            }
        }

        curY += 20f

        // 3. Fund-by-Fund Diagnostic Breakdown
        paint.color = AndroidColor.rgb(15, 23, 42)
        paint.textSize = 12f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("4. ACTIVE SCHEMES & CONSTITUENT SUMMARY", 32f, curY, paint)

        curY += 12f
        paint.color = AndroidColor.rgb(100, 116, 139)
        paint.textSize = 8f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Individual mutual fund allocations, expense ratios, and primary holdings", 32f, curY, paint)

        curY += 10f

        // Scheme Table Header
        drawSchemeRow(
            canvas = canvas,
            paint = paint,
            y = curY,
            isHeader = true,
            name = "Mutual Fund Scheme",
            category = "Category",
            ter = "TER",
            value = "Current Value",
            topHoldings = "Top Holdings"
        )
        curY += 18f

        val sortedSchemes = portfolio.schemes.sortedByDescending { it.currentValue }.take(10)
        for (scheme in sortedSchemes) {
            val top3Holdings = scheme.holdings.take(3).joinToString(", ") { it.ticker }.ifBlank { "Look-Through Synthesized" }
            drawSchemeRow(
                canvas = canvas,
                paint = paint,
                y = curY,
                isHeader = false,
                name = scheme.schemeName.take(28),
                category = scheme.category.take(14),
                ter = String.format(Locale.US, "%.2f%%", scheme.expenseRatio),
                value = inrFormatter.format(scheme.currentValue),
                topHoldings = top3Holdings.take(28)
            )
            curY += 16f
        }

        // 4. Compliance & Methodology Disclaimer
        val footerY = PAGE_HEIGHT - 65f
        paint.color = AndroidColor.rgb(226, 232, 240)
        canvas.drawLine(32f, footerY, PAGE_WIDTH - 32f, footerY, paint)

        paint.color = AndroidColor.rgb(100, 116, 139)
        paint.textSize = 7f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText("DISCLAIMER & METHODOLOGY NOTE:", 32f, footerY + 14f, paint)

        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        paint.textSize = 6.5f
        paint.color = AndroidColor.rgb(148, 163, 184)
        canvas.drawText(
            "This report is generated locally by FinBaba Vault Core using deterministic look-through constituent aggregation and AMFI live NAV data.",
            32f,
            footerY + 25f,
            paint
        )
        canvas.drawText(
            "Mutual fund investments are subject to market risks. Read all scheme related documents carefully. Past performance does not guarantee future returns.",
            32f,
            footerY + 35f,
            paint
        )

        paint.textAlign = Paint.Align.RIGHT
        canvas.drawText("Page 2 of 2 • Generated with FinBaba Studio", PAGE_WIDTH - 32f, footerY + 45f, paint)
        paint.textAlign = Paint.Align.LEFT
    }

    private fun drawTableRow(
        canvas: Canvas,
        paint: Paint,
        y: Float,
        isHeader: Boolean,
        c1: String,
        c2: String,
        c3: String,
        c4: String,
        c5: String
    ) {
        val bgPaint = Paint()
        if (isHeader) {
            bgPaint.color = AndroidColor.rgb(241, 245, 249)
            canvas.drawRect(32f, y - 10f, PAGE_WIDTH - 32f, y + 6f, bgPaint)
            paint.color = AndroidColor.rgb(71, 85, 105)
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            paint.textSize = 8f
        } else {
            paint.color = AndroidColor.rgb(15, 23, 42)
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            paint.textSize = 8f
        }

        canvas.drawText(c1, 38f, y, paint)
        canvas.drawText(c2, 210f, y, paint)
        canvas.drawText(c3, 310f, y, paint)
        canvas.drawText(c4, 400f, y, paint)
        canvas.drawText(c5, 475f, y, paint)
    }

    private fun drawSectorRow(
        canvas: Canvas,
        paint: Paint,
        y: Float,
        isHeader: Boolean,
        rank: String,
        name: String,
        instruments: String,
        weight: String,
        rupees: String
    ) {
        if (isHeader) {
            val bgPaint = Paint().apply { color = AndroidColor.rgb(241, 245, 249) }
            canvas.drawRect(32f, y - 10f, PAGE_WIDTH - 32f, y + 6f, bgPaint)
            paint.color = AndroidColor.rgb(71, 85, 105)
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            paint.textSize = 8f
        } else {
            paint.color = AndroidColor.rgb(15, 23, 42)
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            paint.textSize = 8f
        }

        canvas.drawText(rank, 38f, y, paint)
        canvas.drawText(name, 70f, y, paint)
        canvas.drawText(instruments, 260f, y, paint)
        canvas.drawText(weight, 370f, y, paint)
        canvas.drawText(rupees, 460f, y, paint)
    }

